                <h3>Common Type of Mass Tort Action</h3>
                <p>Since a significant number of mass tort cases involve some form of negligence, the main categories are as follows.</p>
                <ul>
                    <li class="text-wrap">
                        <strong>Medical Device Injuries.</strong> Per regulations set by the Food and Drug Administration (FDA), for an instrument, apparatus, or machine to be considered a medical device, it must aid in diagnosing, preventing, treating, or curing a disease or affecting the structure or function of the body. But sometimes, manufacturers create defective products that fall below the industry standard and cause patients to sustain serious injuries and even death. The types of injuries caused by defective medical devices include heart attack, organ loss, allergic reactions, permanent disability, chronic pain, tissue or bone damage, infections, and stroke.
                    </li>
                    <li class="text-wrap">
                        <strong>Prescription Drug Injuries.</strong> When the FDA approves a drug, it means that the benefits outweigh every known and potential risk. And even though pharmaceutical companies go through the rigorous testing and approval processes set by the FDA’s Center for Drug Evaluation and Research (CDER), some of the drugs end up being dangerous and carry devastating health consequences for the intended population. When this happens, they are removed from the market and the pharmaceutical company will likely be held liable. With the help of our defective drug attorneys, a claim can also be filed against the medical practitioner if they prescribed the drug incorrectly.
                    </li>
                    <li class="text-wrap">
                        <strong>Product Liability Injuries. </strong> According to statistics by the Consumer Product Safety Commission (CPSC), many people suffer injuries or lose their lives each year from using or bringing dangerous or defective products into their homes. Some of the common products that threaten the lives and wellbeing of consumers include contaminated food, defective electronic devices, malfunctioning car parts, and dangerous toys for kids. In a mass tort action litigation, the parties that can be held liable for product liability injuries include the product manufacturer, the manufacturer of the raw materials or parts, the marketing parties, the wholesaler, and the retailer that put the product in the hands of the consumer.
                    </li>
                </ul>

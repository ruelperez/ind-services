                <h3>How Long Does a Mass Tort Action Take?</h3>
                <p>Due to the nature of mass tort cases, they are of course more complex than standard personal injury claims. Also, since they typically involve massive payouts to the plaintiffs, they can and often do take years before both parties arrive at a resolution.</p>
